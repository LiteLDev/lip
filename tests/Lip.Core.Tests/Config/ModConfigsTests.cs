using System.IO.Abstractions.TestingHelpers;
using System.Text.Json;
using System.Text.Json.Nodes;
using Lip.Core.Config;
using Lip.Core.Mcmod;

namespace Lip.Core.Tests.Config;

/// The configuration files of mods, and the JSON files of the configuration
/// (protocol/lip-tui.md, "Configuration").
public class ModConfigsTests {
  private static readonly string _root = OperatingSystem.IsWindows() ? @"C:\ws" : "/ws";

  private static LockedPackage Package(string id, string assetType, params string[] files) =>
      new() {
        Manifest = JsonSerializer.SerializeToElement(new JsonObject {
          ["format"] = 4,
          ["id"] = id,
          ["version"] = "1.0.0",
          ["variants"] = new JsonObject {
            [""] = new JsonArray(new JsonObject {
              ["side"] = "server",
              ["platform"] = "win-x64",
              ["assets"] = new JsonArray(new JsonObject {
                ["type"] = assetType,
                ["urls"] = new JsonArray("https://example.com/a.zip"),
              }),
            }),
          },
        }),
        Variant = "",
        Explicit = true,
        Source = id,
        Files = [.. files],
      };

  private static string P(params string[] segments) => Path.Join([_root, .. segments]);

  [Fact]
  public void Find_ListsTheFilesOfEachInstalledMod() {
    MockFileSystem fs = new(new Dictionary<string, MockFileData> {
      [P("mods", "Alpha", "manifest.json")] = "{}",
      [P("mods", "Alpha", "config", "config.json")] = "{}",
      [P("mods", "Alpha", "config", "sub", "more.yml")] = "",
      [P("mods", "Alpha", "data.json")] = "{}",
      [P("mods", "Money", "manifest.json")] = "{}",
      [P("mods", "Money", "money.json")] = "{}",
      [P("mods", "Money", "Backup.INI")] = "",
      [P("mods", "Money", "Money.dll")] = "",
      [P("mods", "Money", "data", "config.json")] = "{}",
      [P("mods", "Money", "data", "other.json")] = "{}",
      [P("mods", "Fresh", "manifest.json")] = "{}",
      [P("mods", "Loose", "config.json")] = "{}",
    }, _root);
    LockFile lockFile = new() {
      Side = "server",
      Platform = "win-x64",
      Packages = [
        Package("github.com/a/alpha", "mcmod", "mods/Alpha/manifest.json", "mods/Alpha/a.dll"),
        Package("github.com/a/money", "mcmod", "mods/Money/Money.dll", "mods/Money/manifest.json"),
        Package("github.com/a/fresh", "mcmod", "mods/Fresh/manifest.json"),
        // A file package that writes below mods is not a mod.
        Package("github.com/a/loose", "zip", "mods/Loose/config.json"),
      ],
    };

    IReadOnlyList<ModConfig> mods = ModConfigs.Find(fs, _root, lockFile);

    Assert.Equal(["Alpha", "Money", "Fresh"], mods.Select(m => m.ModName));
    Assert.Equal(
        ["mods/Alpha/config/config.json", "mods/Alpha/config/sub/more.yml"], mods[0].Files);
    Assert.Equal(
        ["mods/Money/Backup.INI", "mods/Money/data/config.json", "mods/Money/money.json"],
        mods[1].Files);
    Assert.Empty(mods[2].Files);
    Assert.Equal("github.com/a/money", mods[1].Identity);
  }

  [Fact]
  public void Find_WithoutAStateFile_FindsNothing() {
    Assert.Empty(ModConfigs.Find(new MockFileSystem(), _root, null));
  }

  [Fact]
  public void JsonConfigFile_KeepsTheOrderOfMembersAndDropsComments() {
    JsonNode node = JsonConfigFile.Parse("""
        {
          // generated by the mod
          "version": 3,
          "zeta": true,
          "alpha": {"b": 1, "a": [1, 2,],},
        }
        """);
    node["alpha"]!["b"] = 2;

    Assert.Equal(
        "{\n    \"version\": 3,\n    \"zeta\": true,\n    \"alpha\": {\n        \"b\": 2,\n"
            + "        \"a\": [\n            1,\n            2\n        ]\n    }\n}\n",
        JsonConfigFile.Serialize(node));
    Assert.True(JsonConfigFile.IsReadOnly(node, "version"));
    Assert.False(JsonConfigFile.IsReadOnly(node, "zeta"));
    Assert.False(JsonConfigFile.IsReadOnly(node["alpha"], "b"));
    Assert.Throws<JsonException>(() => JsonConfigFile.Parse("{\"a\": 1, \"a\": 2}"));
  }

  [Theory]
  [InlineData("true", "false", "false")]
  [InlineData("1", "2.5", "2.5")]
  [InlineData("\"x\"", "hello world", "\"hello world\"")]
  [InlineData("null", "7", "7")]
  [InlineData("null", "seven", "\"seven\"")]
  public void TryEdit_KeepsTheKindOfTheValue(string current, string text, string expected) {
    Assert.True(JsonConfigFile.TryEdit(
        JsonNode.Parse(current), text, out JsonNode? value, out string? error));
    Assert.Null(error);
    Assert.Equal(expected, value?.ToJsonString() ?? "null");
  }

  [Theory]
  [InlineData("true", "yes")]
  [InlineData("1", "one")]
  [InlineData("1", "\"1\"")]
  public void TryEdit_AValueOfAnotherKind_Fails(string current, string text) {
    Assert.False(JsonConfigFile.TryEdit(JsonNode.Parse(current), text, out _, out string? error));
    Assert.NotNull(error);
  }

  [Fact]
  public void PlayerLists_AddAndChangePlayers() {
    JsonArray allowlist = PlayerLists.Parse(null);
    PlayerLists.Allow(allowlist, "Steve", "");
    PlayerLists.Allow(allowlist, "Alex", "123");
    Assert.Equal(
        """[{"ignoresPlayerLimit":false,"name":"Steve"},"""
            + """{"ignoresPlayerLimit":false,"name":"Alex","xuid":"123"}]""",
        allowlist.ToJsonString());

    JsonArray permissions = PlayerLists.Parse("""[{"permission": "member", "xuid": "1"}]""");
    PlayerLists.SetPermission(permissions, "1", "operator");
    PlayerLists.SetPermission(permissions, "2", "visitor");
    Assert.Equal(
        """[{"permission":"operator","xuid":"1"},{"permission":"visitor","xuid":"2"}]""",
        permissions.ToJsonString());
    Assert.Throws<ArgumentException>(() => PlayerLists.SetPermission(permissions, "1", "admin"));
    Assert.Throws<JsonException>(() => PlayerLists.Parse("{}"));
  }
}
